  // اللغة: ?lang=en في الرابط (وبتتحفظ) ← المحفوظة ← العربي. زي صفحات الموقع (js/legal.js) —
  // قبل كده الأداة كانت بتتجاهل ?lang=en، فاللي جاي من رابط إنجليزي كان بيلاقيها بالعربي
  var lang = (function () {
    try {
      var fromUrl = new URLSearchParams(global.location.search).get('lang');
      if (fromUrl === 'ar' || fromUrl === 'en') { localStorage.setItem(LANG_KEY, fromUrl); return fromUrl; }
    } catch (e) { /* تخزين مقفول أو رابط غريب */ }
    try {
      var saved = localStorage.getItem(LANG_KEY);
      if (saved === 'ar' || saved === 'en') return saved;
    } catch (e) { /* تخزين مقفول */ }
    return 'ar';
  })();

  function t(key, vars) {
    var s = DICT[lang] && DICT[lang][key];
    if (s == null) s = DICT.ar[key];
    if (s == null) return key;
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, function (m, k) { return vars[k] != null ? String(vars[k]) : m; });
  }

  // صيغة الاسم مع العدد: 'one' أو 'many'.
  // إنجليزي: 1 = مفرد. عربي: من ٣ لـ ١٠ (وآخر رقمين في الأعداد الكبيرة) جمع، والباقي مفرد —
  // "٥ إعلانات" و"١٥ إعلان" و"١٠٣ إعلانات". الصفر بياخد الجمع في اللغتين
  function form(n) {
    n = Math.abs(Math.round(Number(n) || 0));
    if (lang === 'en') return n === 1 ? 'one' : 'many';
    var m = n % 100;
    return (n === 0 || (m >= 3 && m <= 10)) ? 'many' : 'one';
  }
  // أنهي مفتاح يتقري مع العدد: الجمع، أو المفرد، أو (في العربي من ١١ لـ ٩٩) التمييز المنصوب
  // «١٥ إعلاناً / ١٥ تحويلاً» لو مفتاحه موجود — وإلا المفرد («١٥ نقرة» شكلها واحد)
  function countKey(n, oneKey, manyKey, accKey) {
    if (form(n) === 'many') return manyKey;
    if (lang === 'ar' && accKey && DICT.ar[accKey] != null && Math.abs(Math.round(Number(n) || 0)) % 100 >= 11) return accKey;
    return oneKey;
  }
  // الاسم المناسب للعدد: base + '.one' / '.many' / '.acc'
  function noun(n, base) { return t(countKey(n, base + '.one', base + '.many', base + '.acc')); }
  // الجمع بعد «أي» أو بعد عدد من ٣ لـ ١٠ مجرور: «دون أي عملاء محتملين» / «٥ عملاء محتملين» —
  // resG موجود بس للأنواع اللي شكلها بيتغيّر (جمع المذكر السالم)، والباقي بياخد res زي ما هو
  function resultAny(key) {
    key = key || 'generic';
    return t(lang === 'ar' && DICT.ar['resG.' + key] != null ? 'resG.' + key : 'res.' + key);
  }
  // اسم نوع النتيجة مظبوط على العدد: res1 (مفرد) / res أو resG (جمع) / resA (منصوب)
  function resultNoun(n, key) {
    key = key || 'generic';
    var k = countKey(n, 'res1.' + key, 'res.' + key, 'resA.' + key);
    return k === 'res.' + key ? resultAny(key) : t(k);
  }
  // عدد + نوع النتيجة جوه جملة. digits = دالة كتابة الرقم (عربي/إنجليزي).
  // في العربي ١ و٢ بيتكتبوا من غير رقم («عملية شراء واحدة»، «عمليتي شراء») — «١ عملية شراء» و«٢ عملية شراء» مش فصحى
  function countPhrase(n, key, digits) {
    key = key || 'generic';
    n = Math.round(Number(n) || 0);
    if (lang === 'ar' && n === 1 && DICT.ar['resOne.' + key] != null) return DICT.ar['resOne.' + key];
    if (lang === 'ar' && n === 2 && DICT.ar['res2.' + key] != null) return DICT.ar['res2.' + key];
    return (digits ? digits(n) : String(n)) + ' ' + resultNoun(n, key);
  }
  // «نحو ضعف متوسطه» / «٣ أضعاف» / «٢٫٦ ضعف» / «١٥ ضعفاً» — «٢ أضعاف» مش فصحى. بالإنجليزي «2.6×»
  function timesPhrase(x, digits) {
    var r = Math.round((Number(x) || 0) * 10) / 10;
    var d = digits ? digits(r) : String(r);
    if (lang !== 'ar') return d + '×';
    if (r === 2) return 'ضعف';
    if (r === Math.round(r) && r >= 3 && r <= 10) return d + ' أضعاف';
    if (r === Math.round(r) && r >= 11) return d + ' ضعفاً';
    return d + ' ضعف';
  }
  // عدد بكسر أو من غير («٤٫٥ مرة» / «٧ مرات» / «4.5 times»): الكسر في العربي بياخد المفرد، وفي الإنجليزي الجمع
  function measureNoun(v, base) {
    var r = Math.round((Number(v) || 0) * 10) / 10;
    if (r !== Math.round(r)) return t(base + (lang === 'ar' ? '.one' : '.many'));
    return noun(r, base);
  }

  // بيترجم عناصر الـ HTML اللي عليها data-i18n (النص)، و data-i18n-placeholder / -title / -aria
  function apply(root) {
    root = root || document;
    Array.prototype.forEach.call(root.querySelectorAll('[data-i18n]'), function (el) { el.textContent = t(el.getAttribute('data-i18n')); });
    Array.prototype.forEach.call(root.querySelectorAll('[data-i18n-placeholder]'), function (el) { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder'))); });
    Array.prototype.forEach.call(root.querySelectorAll('[data-i18n-title]'), function (el) { el.setAttribute('title', t(el.getAttribute('data-i18n-title'))); });
    Array.prototype.forEach.call(root.querySelectorAll('[data-i18n-aria]'), function (el) { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });
  }

  function setDocumentLang() {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  }

  function setLang(next) {
    if (next !== 'ar' && next !== 'en') return;
    lang = next;
    try { localStorage.setItem(LANG_KEY, lang); } catch (e) { /* مش مهم */ }
    setDocumentLang();
    apply(document);
  }

