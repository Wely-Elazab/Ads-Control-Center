      var diff = function (a, b) { return Object.keys(DICT[a]).filter(function (k) { return !(k in DICT[b]) && !/\.acc$|^res(A|G|One|2)\./.test(k); }); };
      return { missingInEn: diff('ar', 'en'), missingInAr: diff('en', 'ar') };
