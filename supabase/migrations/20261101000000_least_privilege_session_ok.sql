-- مُدقِّق Supabase بلّغ إن public.session_ok مفتوحة للدورين anon وauthenticated.
-- اللي بينادي الدالة فعلاً اتنين بس:
--   ١) الـ Worker (Live/api/_login.js) بالمفتاح العام  → محتاج anon
--   ٢) دالة sync (auth.ts) بالمفتاح السري             → محتاج service_role
-- مفيش ولا سطر في المتصفح بينادي قاعدة البيانات مباشرة (اتأكدنا بالبحث في Live/js كله)،
-- يعني الدور authenticated مكانش مستعمل خالص. بنسحبه.
--
-- anon بيفضل عن قصد: ده تصميم الـ Worker. والمخاطرة مقبولة لأن الدالة:
--   - بترجّع صح/غلط بس، ومش بترجّع أي بيانات
--   - محتاجة رقمين عشوائيين صح مع بعض (جلسة + صاحبها) = ٢٤٤ بت
--   - مسار بحثها مثبّت (set search_path = '')
revoke execute on function public.session_ok(uuid, uuid) from authenticated;
